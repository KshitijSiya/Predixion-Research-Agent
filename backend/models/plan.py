from typing import List, Literal
from pydantic import BaseModel, Field

class SubTask(BaseModel):
    """
    An individual sub-question/task within the research plan.
    """
    id: int = Field(..., description="Unique step number.")
    description: str = Field(..., description="What this step investigates.")
    search_query: str = Field(..., description="Exact search query to execute for this step.")
    tool: Literal["web_search", "web_scrape", "synthesis"] = Field(
        default="web_search", 
        description="Tool assigned to this step."
    )

class ResearchPlan(BaseModel):
    """
    The structured plan generated by the Planner before tool execution.
    """
    original_query: str = Field(..., description="The user's original query.")
    reasoning: str = Field(..., description="Chain of thought explaining the research approach.")
    sub_tasks: List[SubTask] = Field(
        ..., 
        description="List of 2 to 4 decomposed sub-tasks to execute."
    )
    key_entities: List[str] = Field(
        default_factory=list, 
        description="Key entities, companies, or concepts identified."
    )
